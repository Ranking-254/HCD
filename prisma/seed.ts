async function main() {
  console.log("🌱 Starting vehicle database seed...");

  for (const car of vehiclesData) {
    const { images, ...vehicleDetails } = car;

    const upsertedVehicle = await prisma.vehicle.upsert({
      where: { stockNumber: vehicleDetails.stockNumber },
      update: {
        ...vehicleDetails,
        priceKes: vehicleDetails.priceKes,
        previousPriceKes: vehicleDetails.previousPriceKes,
      },
      create: {
        ...vehicleDetails,
        priceKes: vehicleDetails.priceKes,
        previousPriceKes: vehicleDetails.previousPriceKes,
      },
    });

    // Remove existing image records for this vehicle to avoid duplicates
    await prisma.vehicleImage.deleteMany({
      where: { vehicleId: upsertedVehicle.id },
    });

    // Insert gallery images with order index and designated cover
    await prisma.vehicleImage.createMany({
      data: images.map((url, index) => ({
        vehicleId: upsertedVehicle.id,
        url,
        publicId: `seed-${upsertedVehicle.stockNumber}-${index}`,
        order: index,
        isCover: index === 0,
      })),
    });

    console.log(
      `✓ Seeded: ${upsertedVehicle.year} ${upsertedVehicle.make} ${upsertedVehicle.model} [${upsertedVehicle.stockNumber}]`,
    );
  }

  console.log(
    "🚀 Finished seeding 20 vehicles with full multi-image galleries!",
  );
}

main()
  .catch((e) => {
    console.error("❌ Seed error:", e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
